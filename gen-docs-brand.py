#!/usr/bin/env python3
"""Give a consumer's docs sites the product's own identity, read from its frontend.

The frontend is the source: its colour tokens (shadcn-style `--primary:
H S% L%` custom properties), its logo and its favicon. This copies them into
every docs site, so a rebrand of the app reaches the docs on the next build and
the two never drift.

Run from the consumer's root (`make docs-sync` runs it after the stubs):

    python3 devtools/gen-docs-brand.py [--check]

It writes, for each site in docs-site/sites.json:

    docs-site/<site>/assets/brand/brand.css   Material's colour variables, light and dark
    docs-site/<site>/assets/brand/logo.<ext>  the product logo
    docs-site/<site>/assets/brand/favicon.ico

and makes each mkdocs.<site>.yml use them (palette `custom`, theme logo and
favicon, extra_css). The landing page and the error pages get the same
colours and favicon between their `<!-- brand -->` and `<!-- /brand -->`
markers.

Where to read the brand comes from a "brand" entry in docs-site/sites.json;
every key is optional:

    "brand": {
      "css": "frontend/src/assets/css/index.css",
      "light": ":root",
      "dark": ".dark",
      "logo": "frontend/public/icons/<product>-logo.svg",
      "favicon": "frontend/public/favicon.ico",
      "pages": ["docs-site/landing.html", "infra/docs-errors/*.html"]
    }

Without "logo", the first frontend/public/icons/*-logo.svg is used.
"""
import argparse
import io
import json
import pathlib
import re
import sys

REPO = pathlib.Path.cwd()
DEFAULTS = {
    "css": "frontend/src/assets/css/index.css",
    "light": ":root",
    "dark": ".dark",
    "favicon": "frontend/public/favicon.ico",
    "pages": ["docs-site/landing.html", "infra/docs-errors/*.html"],
}
TOKENS = ("primary", "primary-foreground", "ring", "background", "foreground",
          "muted-foreground", "border")
HEADER = "/* Generated by devtools/gen-docs-brand.py from the frontend's tokens: do not edit. */\n"


def tokens(css: str, selector: str, source: str) -> dict:
    """The custom properties declared in the block whose selector is exactly `selector`."""
    m = re.search(r"(^|[\s}])" + re.escape(selector) + r"\s*\{([^}]*)\}", css)
    if not m:
        raise SystemExit(f"{source}: no `{selector} {{ … }}` block")
    found = dict(re.findall(r"--([a-z-]+)\s*:\s*([^;]+);", m.group(2)))
    missing = [t for t in ("primary", "primary-foreground") if t not in found]
    if missing:
        raise SystemExit(f"{source} `{selector}`: no --{', --'.join(missing)}")
    return {t: found[t].strip() for t in TOKENS if t in found}


def hsl(value: str, alpha: str = "") -> str:
    return f"hsl({value}{' / ' + alpha if alpha else ''})"


def rgb(value: str) -> tuple:
    """`H S% L%` as 0-1 sRGB."""
    h, s, l = (float(x.rstrip("%")) for x in value.split()[:3])
    s, l = s / 100, l / 100
    c = (1 - abs(2 * l - 1)) * s
    x = c * (1 - abs((h / 60) % 2 - 1))
    r, g, b = [(c, x, 0), (x, c, 0), (0, c, x), (0, x, c), (x, 0, c), (c, 0, x)][int(h // 60) % 6]
    m = l - c / 2
    return (r + m, g + m, b + m)


def contrast(a: tuple, b: tuple) -> float:
    def lum(c):
        lin = [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in c]
        return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2]
    hi, lo = sorted((lum(a), lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def readable(colour: str, background: str) -> str:
    """The brand colour, moved toward white (on a dark page) or black (on a light
    one) only as far as body text needs to reach WCAG AA (4.5:1). The app uses
    the colour on buttons; the docs use it for running text links."""
    fg, bg = rgb(colour), rgb(background)
    if contrast(fg, bg) >= 4.5:
        return hsl(colour)
    toward = (1.0, 1.0, 1.0) if sum(bg) < 1.5 else (0.0, 0.0, 0.0)
    for pct in range(5, 100, 5):
        mixed = tuple(f + (t - f) * pct / 100 for f, t in zip(fg, toward))
        if contrast(mixed, bg) >= 4.5:
            target = "white" if toward[0] else "black"
            return f"color-mix(in srgb, {hsl(colour)} {100 - pct}%, {target})"
    return hsl(colour)


def material_vars(t: dict) -> str:
    accent = t.get("ring", t["primary"])
    lines = [
        f"--md-primary-fg-color: {hsl(t['primary'])};",
        f"--md-primary-fg-color--light: {hsl(t['primary'], '0.8')};",
        f"--md-primary-fg-color--dark: {hsl(t['primary'])};",
        f"--md-primary-bg-color: {hsl(t['primary-foreground'])};",
        f"--md-primary-bg-color--light: {hsl(t['primary-foreground'], '0.7')};",
        f"--md-accent-fg-color: {hsl(accent)};",
        f"--md-accent-fg-color--transparent: {hsl(accent, '0.1')};",
        f"--md-typeset-a-color: {readable(accent, t.get('background', '0 0% 100%'))};",
    ]
    if "background" in t:
        lines.append(f"--md-default-bg-color: {hsl(t['background'])};")
    return "".join(f"  {line}\n" for line in lines)


def brand_css(light: dict, dark: dict) -> str:
    return (HEADER
            + ':root, [data-md-color-scheme="default"] {\n' + material_vars(light) + "}\n"
            + '[data-md-color-scheme="slate"] {\n' + material_vars(dark) + "}\n")


def page_vars(t: dict) -> str:
    pairs = [("brand", t.get("ring", t["primary"])), ("bg", t.get("background")),
             ("fg", t.get("foreground")), ("muted", t.get("muted-foreground")),
             ("line", t.get("border"))]
    return " ".join(f"--{k}:{hsl(v)};" for k, v in pairs if v)


def page_block(light: dict, dark: dict, favicon_href: str) -> str:
    return ("<!-- brand -->\n"
            f'<link rel="icon" href="{favicon_href}">\n'
            f"<style>:root{{ {page_vars(light)} }} "
            f"@media (prefers-color-scheme: dark){{ :root{{ {page_vars(dark)} }} }}</style>\n"
            "<!-- /brand -->")


def ensure_config(text: str) -> str:
    """mkdocs.<site>.yml uses the brand: custom palette, logo, favicon, extra_css."""
    text = re.sub(r"(\n      primary:) [\w-]+\n(?!      accent: custom)", r"\1 custom\n      accent: custom\n", text)
    text = re.sub(r"(\n      primary:) (?!custom)[\w-]+\n", r"\1 custom\n", text)
    if "\n  logo:" not in text.split("\nplugins:")[0]:
        text = text.replace("theme:\n  name: material\n",
                            "theme:\n  name: material\n  logo: LOGO\n  favicon: assets/brand/favicon.ico\n", 1)
    if "\nextra_css:" not in text:
        text = text.replace("\nplugins:", "\nextra_css:\n  - assets/brand/brand.css\n\nplugins:", 1)
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail instead of writing (CI)")
    args = ap.parse_args()

    conf = json.load(io.open(REPO / "docs-site" / "sites.json", encoding="utf-8"))
    brand = {**DEFAULTS, **conf.get("brand", {})}
    css_path = REPO / brand["css"]
    css = css_path.read_text(encoding="utf-8")
    light = tokens(css, brand["light"], brand["css"])
    dark = tokens(css, brand["dark"], brand["css"])

    logo = brand.get("logo")
    if not logo:
        found = sorted((REPO / "frontend/public/icons").glob("*-logo.svg"))
        if not found:
            raise SystemExit("no brand.logo in sites.json and no frontend/public/icons/*-logo.svg")
        logo = found[0].relative_to(REPO).as_posix()
    logo_path, favicon_path = REPO / logo, REPO / brand["favicon"]
    for p in (logo_path, favicon_path):
        if not p.exists():
            raise SystemExit(f"{p.relative_to(REPO)} not found")
    logo_name = "logo" + logo_path.suffix

    want: dict[pathlib.Path, bytes] = {}
    sites = list(conf["sites"])
    for site in sites:
        out = REPO / "docs-site" / site / "assets" / "brand"
        want[out / "brand.css"] = brand_css(light, dark).encode()
        want[out / logo_name] = logo_path.read_bytes()
        want[out / "favicon.ico"] = favicon_path.read_bytes()
        config = REPO / f"mkdocs.{site}.yml"
        if config.exists():
            text = config.read_text(encoding="utf-8")
            want[config] = ensure_config(text).replace("logo: LOGO", f"logo: assets/brand/{logo_name}").encode()

    # The landing page and the error pages live outside every site; they link
    # the favicon of the first site the server serves (one with roots).
    served = next((s for s in sites if conf["sites"][s].get("roots")), sites[0])
    block = page_block(light, dark, f"/{served}/assets/brand/favicon.ico")
    marker = re.compile(r"<!-- brand -->.*?<!-- /brand -->", re.S)
    for pattern in brand["pages"]:
        for page in sorted(REPO.glob(pattern)):
            text = page.read_text(encoding="utf-8")
            if not marker.search(text):
                print(f"{page.relative_to(REPO)}: no <!-- brand --> … <!-- /brand --> markers, left as is",
                      file=sys.stderr)
                continue
            want[page] = marker.sub(lambda _: block, text).encode()

    stale = [p for p, data in want.items() if not p.exists() or p.read_bytes() != data]
    if args.check:
        if stale:
            print("docs brand is out of sync with the frontend:", file=sys.stderr)
            for p in stale:
                print(f"  {p.relative_to(REPO)}", file=sys.stderr)
            print("\nRun: make docs-sync", file=sys.stderr)
            return 1
        print(f"docs brand in sync ({len(sites)} sites, from {brand['css']})")
        return 0
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(want[p])
    print(f"docs brand: {len(stale)} file(s) written for {len(sites)} sites, from {brand['css']} and {logo}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
